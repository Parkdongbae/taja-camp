const CODE: Record<Subject, string> = { korean: 'kor', english: 'eng', math: 'mat', science: 'sci', social: 'soc', basic: 'bas' };
const pad = (n: number) => String(n).padStart(3, '0');

function build() {
  const words: WordItem[] = [];
  const sentences: SentenceItem[] = [];
  const count: Record<string, number> = {};
  const next = (kind: string, subject: Subject) => {
    const key = `${kind}-${subject}`;
    count[key] = (count[key] ?? 0) + 1;
    return `${kind}-in-${CODE[subject]}-${pad(count[key])}`;
  };
  for (const u of UNITS) {
    for (const [text, meaning] of u.words) {
      words.push({ id: next('w', u.subject), text, meaning, lang: u.lang, subject: u.subject, unit: u.unit, level: 2 });
    }
    for (const text of u.sentences) {
      sentences.push({ id: next('s', u.subject), text, lang: u.lang, subject: u.subject, unit: u.unit, level: 2 });
    }
  }
  const passages: PassageItem[] = PASSAGES.map((p) => ({ id: next('p', p.subject), ...p, level: 2 }));
  return { words, sentences, passages };
}

const built = build();
export const SUBJECT_WORDS = built.words;
export const SUBJECT_SENTENCES = built.sentences;
export const SUBJECT_PASSAGES = built.passages;
